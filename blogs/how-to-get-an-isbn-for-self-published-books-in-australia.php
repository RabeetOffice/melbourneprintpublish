                        <h2 id="toc-16"><span style="font-weight: 400;">The Lesser-Known Publication Numbers</span></h2>
                        <p><span style="font-weight: 400;">ISBNs get all the attention, but they are not the only
                                identification system in the publishing world. There are other codes designed for other
                                types of publications, and if you are venturing beyond traditional books, you may
                                encounter them.</span></p>
                        <h2 id="toc-17"><span style="font-weight: 400;">Let us look at the two most common
                                alternatives.</span></h2>
                        <p><span style="font-weight: 400;">ISSN: The Identifier for Periodicals</span></p>
                        <p><span style="font-weight: 400;">The International Standard Serial Number, or ISSN, is the
                                equivalent of an ISBN but for serial publications. That includes magazines, journals,
                                newspapers, annual reports, and any publication that is issued on a recurring
                                basis.</span></p>
                        <p><span style="font-weight: 400;">Why do periodicals not use ISBNs? Because ISBNs are designed
                                for one-off publications. Each ISBN identifies a specific edition of a specific work. A
                                magazine, on the other hand, is published weekly, monthly, or quarterly, with different
                                content each time. Assigning a new ISBN to every issue would be impractical and would
                                defeat the purpose of the system.</span></p>
                        <p><span style="font-weight: 400;">The ISSN solves this by identifying the serial as a whole
                                rather than individual issues. A magazine gets one ISSN, and that number covers every
                                issue published under that title. If the magazine changes its name, it gets a new ISSN,
                                but individual issues do not need their own numbers.</span></p>
                        <p><span style="font-weight: 400;">Who needs an ISSN? If you are publishing a journal, a
                                newsletter, a magazine, or any recurring publication, you will need one. Libraries and
                                academic institutions rely heavily on ISSNs to manage their subscriptions and catalogue
                                their holdings. If your serial publication needs to be discoverable in these systems, an
                                ISSN is essential.</span></p>
                        <p><span style="font-weight: 400;">In Australia, ISSNs are issued by the National Library of
                                Australia, not Thorpe-Bowker. The process is separate from ISBN registration.</span></p>
                        <h2 id="toc-18"><span style="font-weight: 400;">ISMN: The Identifier for Music
                                Publications</span></h2>
                        <p><span style="font-weight: 400;">The International Standard Music Number, or ISMN, does for
                                printed music what the ISBN does for books. It identifies published music scores, sheet
                                music, and related publications.</span></p>
                        <p><span style="font-weight: 400;">Why does music need its own system? Because music
                                publications are distributed through different channels than books. While books flow
                                through bookshops and libraries, sheet music moves through music retailers, educational
                                suppliers, and specialist distributors. These industries have their own cataloguing
                                systems, and the ISMN is designed to work within them.</span></p>
                        <p><span style="font-weight: 400;">If you are a composer publishing your own scores, or a music
                                publisher producing sheet music, you will need an ISMN. It ensures your publications are
                                properly catalogued in music libraries and databases worldwide.</span></p>
                        <p><span style="font-weight: 400;">In Australia, ISMNs can be obtained through Thorpe-Bowker,
                                the same agency that handles ISBNs.</span></p>
                        <p><span style="font-weight: 400;">Like ISBNs, ISMNs may also require barcodes if the
                                publication is being sold through retail channels. The process for obtaining a barcode
                                is similar, either through the issuing agency or a third-party supplier.</span></p>
                        <p><span style="font-weight: 400;">Do ISMNs, ISSNs, and ISBNs Serve the Same Function?</span>
                        </p>
                        <p><span style="font-weight: 400;">In principle, yes. They all serve as unique identifiers for
                                publications. But they operate in different contexts and are not interchangeable.</span>
                        </p>
