                        <h2 id="toc-3"><span style="font-weight: 400;">How to Get an ISBN in Australia</span></h2>
                        <h3 id="toc-4"><span style="font-weight: 400;">Right. Here is the part you actually came
                                for.</span></h3>
                        <p><span style="font-weight: 400;">In Australia, ISBNs are issued by one agency and one agency
                                only: Thorpe-Bowker. They are the officially appointed ISBN agency for Australia, and if
                                you want an Australian ISBN, you go through them. There is no alternative provider, no
                                shortcut, and no workaround.</span></p>
                        <p><span style="font-weight: 400;">Some authors get confused by this because in other countries,
                                particularly the United States, you can technically get a free ISBN through certain
                                publishing platforms. In Australia, that is not how it works. Thorpe-Bowker is the sole
                                source, and there is a cost involved.</span></p>
                        <h3 id="toc-5"><span style="font-weight: 400;">Here is the step-by-step process.</span></h3>
                        <p><span style="font-weight: 400;">First, visit the Thorpe-Bowker website. Their ISBN
                                registration portal is straightforward and has been designed with self-publishers in
                                mind. You do not need to be a registered business or a traditional publishing house to
                                apply. Individual authors can and do register for ISBNs all the time.</span></p>
                        <p><span style="font-weight: 400;">Second, create an account. You will need to provide some
                                basic information about yourself and your publishing activities. If this is your first
                                time, you will be setting up a new publisher profile. Yes, even if you are a solo author
                                self-publishing one book, you are technically the publisher in this scenario, and the
                                system treats you accordingly.</span></p>
                        <p><span style="font-weight: 400;">Third, fill out the application for your ISBN. This is where
                                you provide the details of your book. You will need the title, the author name, the
                                format you are publishing in, and some other metadata. If you have not finalised your
                                title yet, you can still apply, but you will need to update the record before
                                publication.</span></p>
                        <p><span style="font-weight: 400;">Fourth, pay the fee. ISBNs in Australia are not free, but
                                they are not outrageously expensive either. You can purchase a single ISBN or buy them
                                in blocks. If you are planning to publish multiple books, or if you are publishing in
                                multiple formats, buying a block of ISBNs upfront is more cost-effective.</span></p>
                        <p><span style="font-weight: 400;">And that is essentially it. Once your application is
                                processed and your payment goes through, you will be issued your ISBN. The turnaround is
                                usually pretty quick.</span></p>
                        <p><span style="font-weight: 400;">One thing worth mentioning is that the ISBN must be assigned
                                before your book goes to print or is uploaded for digital distribution. It needs to be
                                included in your book’s metadata, printed on the copyright page, and encoded in the
