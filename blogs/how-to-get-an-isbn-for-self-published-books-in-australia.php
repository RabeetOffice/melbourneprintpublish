                        <p><span style="font-weight: 400;">You cannot use an ISBN in place of an ISSN, and you cannot
                                use an ISSN in place of an ISMN. They are distinct systems designed for distinct types
                                of content. If you are publishing across multiple formats or types of content, you may
                                need more than one type of identifier.</span></p>
                        <p><span style="font-weight: 400;">For most authors, the ISBN is the only number you will ever
                                need to worry about. But it is useful to know that these other systems exist,
                                particularly if your publishing activities expand beyond traditional books.</span></p>
                        <h2 id="toc-21"><span style="font-weight: 400;">Practical Tips for Managing Your ISBNs</span>
                        </h2>
                        <p><span style="font-weight: 400;">Now that we have covered the what and the how, let us talk
                                about some practical advice for managing your ISBNs effectively.</span></p>
                        <p><span style="font-weight: 400;">First, keep a record. When you purchase ISBNs, write down
                                which number is assigned to which book and which format. It sounds obvious, but you
                                would be surprised how many authors lose track, especially if they have bought a block
                                of ten and are assigning them over several years.</span></p>
                        <p><span style="font-weight: 400;">Second, do not reuse ISBNs. Once an ISBN has been assigned to
                                a publication, it belongs to that publication forever. If you release a new edition of
                                your book with significant changes, it needs a new ISBN. Minor corrections like fixing
                                typos do not require a new ISBN, but substantial revisions, new forewords, or format
                                changes do.</span></p>
                        <p><span style="font-weight: 400;">Third, assign your ISBN before publication, not after. The
                                ISBN needs to be included in your book’s metadata, on the copyright page, and in the
                                barcode on the back cover. Trying to add it after the fact is messy and can cause
                                distribution problems.</span></p>
                        <p><span style="font-weight: 400;">Fourth, make sure your bibliographic details are accurate.
                                The information you register with Thorpe-Bowker is what will appear in industry
                                databases. If your title changes between registration and publication, update the
                                record. If your author name is different from what you registered, fix it. Inaccurate
                                metadata leads to confusion down the line.</span></p>
                        <p><span style="font-weight: 400;">Fifth, if you are publishing multiple books, think
                                strategically about your ISBNs. Buying in blocks saves money, and having ISBNs ready to
                                assign means you can move faster when your next book is ready for publication.</span>
                        </p>
                        <p><span style="font-weight: 400;">These are small things, but they make a real difference when
                                it comes to running a smooth publishing operation. And if any of this feels like too
