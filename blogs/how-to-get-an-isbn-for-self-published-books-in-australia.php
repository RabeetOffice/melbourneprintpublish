                                registering an ISBN directly through Thorpe-Bowker is the way to go. It gives you
                                ownership of your identifiers and ensures your book is properly catalogued from day
                                one.</span></p>
                        <h2 id="toc-12"><span style="font-weight: 400;">Who Owns the ISBN? Publisher vs Author</span>
                        </h2>
                        <p><span style="font-weight: 400;">This is a question that comes up constantly, and it is
                                important to get it right.</span></p>
                        <p><span style="font-weight: 400;">The ISBN is registered to the publisher. In traditional
                                publishing, that means the publishing house. In self-publishing, that means you, the
                                author, assuming you are the one who registered the ISBN.</span></p>
                        <p><span style="font-weight: 400;">Here is where it gets tricky. Some publishing services,
                                vanity presses, and hybrid publishers will register the ISBN under their own name. This
                                means that in the ISBN database, they are listed as the publisher of your book, not you.
                                Depending on your arrangement with them, this may or may not be an issue.</span></p>
                        <p><span style="font-weight: 400;">If you care about being recognised as the publisher of your
                                own work, and most self-publishing authors do, then you need to be the one who registers
                                the ISBN. When you go through Thorpe-Bowker directly, the ISBN is registered to you.
                                Your name or your publishing imprint appears as the publisher. You have full
                                control.</span></p>
                        <p><span style="font-weight: 400;">If someone else supplies the ISBN, they are the registered
                                publisher in the database. That does not necessarily mean they own your book or hold the
                                copyright. Copyright is a separate legal matter, and if you want to understand how that
                                works in the Australian context, it is worth reading up on</span> <a
