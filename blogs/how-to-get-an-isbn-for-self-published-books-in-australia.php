                                gives you a SKU, that SKU means nothing to a bookshop down the road. It means nothing to
                                a library. It means nothing to any other distributor or retailer. It is a closed-loop
                                identifier.</span></p>
                        <p><span style="font-weight: 400;">An ISBN, on the other hand, is universal. It works
                                everywhere. Every bookshop, every library, every distributor, every database in the
