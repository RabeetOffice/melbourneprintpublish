                                style="font-weight: 400;">. But the ISBN registration does affect how your book appears
                                in industry databases, and that has practical implications for distribution and
                                recognition.</span></p>
                        <p><span style="font-weight: 400;">The safest approach, especially if you are working with a
                                publishing service provider, is to ask upfront: who will the ISBN be registered to? If
