                        <p><span style="font-weight: 400;">So you have written a book. Maybe it is a memoir that took
                                you three years and two breakdowns to finish. Maybe it is a children’s picture book
                                about a wallaby who cannot find his way home. Whatever it is, you have done the hard
                                part. You have written the thing. Now comes the part nobody warns you about: the admin.
                                And right at the top of that admin pile sits one question every Australian author
                                eventually asks. How do I get an ISBN?</span></p>
                        <p><span style="font-weight: 400;">It sounds like it should be simple. And honestly, it mostly
                                is. But there is a surprising amount of confusion floating around about ISBNs, what they
                                actually do, whether you truly need one, and where to get one if you are publishing in
                                Australia. Some authors skip this step entirely and regret it later. Others buy ten
                                ISBNs before they have even finished their first draft. Both extremes are avoidable if
                                you just understand the basics.</span></p>
                        <p><span style="font-weight: 400;">This guide is going to walk you through everything. Not just
                                the how, but the why. Because when you understand what an ISBN actually does and how it
                                fits into the broader publishing ecosystem, the whole process stops feeling like red
                                tape and starts feeling like progress. Let us get into it.</span></p>
                        <h2 id="toc-0"><span style="font-weight: 400;">What Exactly Is an ISBN?</span></h2>
                        <p><span style="font-weight: 400;">Before we talk about how to get an ISBN number, it helps to
                                understand what you are actually getting.</span></p>
                        <p><span style="font-weight: 400;">An ISBN, which stands for International Standard Book Number,
                                is a unique numeric identifier assigned to a specific edition of a book. Think of it
                                like a fingerprint for your publication. No two books share the same ISBN, and no single
                                book should have more than one ISBN per format.</span></p>
                        <p><span style="font-weight: 400;">That last part trips people up, so let us be clear. If you
                                are publishing a paperback and a hardcover and an eBook, each of those formats needs its
                                own ISBN. They are not interchangeable. A paperback is not the same product as an eBook,
                                even if the words inside are identical. The ISBN is tied to the format, not just the
                                content.</span></p>
                        <p><span style="font-weight: 400;">Now, the ISBN itself is a 13-digit number. It was not always
                                13 digits long. Older ISBNs were 10 digits, and you will still see 10 ISBN references
                                floating around in older catalogues and databases. But since 2007, the standard has been
                                13 digits, and that is what you will be issued today.</span></p>
                        <p><span style="font-weight: 400;">Those 13 digits are not random. Each section of the number
                                carries specific information. Let us break it down.</span></p>
