                        <h2 id="toc-7"><span style="font-weight: 400;">Getting a Barcode for Your ISBN</span></h2>
                        <p><span style="font-weight: 400;">Once you have your ISBN, the next step is getting a barcode.
                                This is the machine-readable version of your ISBN that appears on the back cover of your
                                printed book. It is what retailers scan at the point of sale, and it is what warehouses
                                use to process stock.</span></p>
                        <p><span style="font-weight: 400;">The barcode is not the same thing as the ISBN. The ISBN is
                                the number. The barcode is the visual representation of that number in a format that
                                scanners can read. You need both.</span></p>
                        <p><span style="font-weight: 400;">You can purchase a barcode directly from Thorpe-Bowker when
                                you register your ISBN. They offer barcode generation as part of their services.
                                Alternatively, you can use a third-party barcode supplier, but make sure the barcode
                                conforms to the correct standard. For books, the standard is EAN-13, which matches the
                                13-digit ISBN format.</span></p>
                        <p><span style="font-weight: 400;">If you are including the recommended retail price on your
                                barcode, which is common for books sold in physical retail, you will also need a
                                supplemental barcode that encodes the price. Your barcode supplier or your publishing
                                team can advise on this.</span></p>
